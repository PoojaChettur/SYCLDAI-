export function createCustomCompanyPreset(
  companyName: string,
  provider: 'aws' | 'gcp' | 'azure' | 'k8s' | 'sandbox',
  clusterName: string,
  region: string
): CompanyCloudPreset {
  const sanitized = companyName.toLowerCase().replace(/[^a-z0-9]/g, '-');
  const services = INITIAL_SERVICES.map((s, idx) => ({
    ...s,
    id: `${sanitized}-${s.id}`,
    name: `${sanitized}-${s.name}`,
    cgroupPath: `/kubepods.slice/${sanitized}-pod-${s.pid}`,
  }));

  return {
    id: `custom-${sanitized}-${Date.now()}`,
    companyName: companyName,
    cloudName: clusterName || `${sanitized}-prod-${provider}`,
    provider,
    regionName: `${provider.toUpperCase()} (${region}) - Dedicated Private Cloud`,
    badge: `${companyName} Sandbox Live`,
    description: `Dedicated ${companyName} cluster with 14 containerized services and active eBPF Sentinel agent.`,
    cluster: {
      id: `cluster-${sanitized}`,
      name: clusterName || `${sanitized}-prod-${provider}`,
      companyName,
      provider,
      isSandbox: true,
      location: `${provider.toUpperCase()} (${region})`,
      kernelVersion: '6.5.0-ebpf-verified',
      activeNodes: 42,
      totalNodes: 42,
      activeServices: 14,
      pingMs: 1.2,
    },
    services,
  };
}
